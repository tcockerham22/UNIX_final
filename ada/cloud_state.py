"""PostgreSQL-backed chat history and memories for Ada's cloud profile."""

from __future__ import annotations

import json
import logging
import threading
import time
from contextlib import contextmanager
from typing import Generator

from .memory import CATEGORIES
from .documents import extract_document_text

LOGGER = logging.getLogger(__name__)


class PostgresState:
    """Provide shared state through PostgreSQL instead of process-local files."""

    def __init__(self, database_url: str | None):
        self.database_url = database_url
        self._schema_lock = threading.Lock()
        self._schema_ready = False

    @contextmanager
    def _connection(self) -> Generator[object, None, None]:
        """Open a short-lived connection and initialize the small schema once."""
        if not self.database_url:
            raise RuntimeError("ADA_DATABASE_URL must be set in the cloud profile.")

        import psycopg

        with psycopg.connect(self.database_url) as connection:
            if not self._schema_ready:
                with self._schema_lock:
                    if not self._schema_ready:
                        self._create_schema(connection)
                        connection.commit()
                        self._schema_ready = True
            yield connection

    @staticmethod
    def _create_schema(connection) -> None:
        """Create only the two shared state tables needed in Phase 1."""
        # Serialize first-time DDL when multiple web replicas start together.
        connection.execute("SELECT pg_advisory_xact_lock(416488673199)")
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS ada_chat_messages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                session_id TEXT NOT NULL,
                role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
                content TEXT NOT NULL,
                sources JSONB NOT NULL DEFAULT '[]'::jsonb,
                created_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )
            """
        )
        connection.execute(
            """
            ALTER TABLE ada_chat_messages
            ADD COLUMN IF NOT EXISTS sources JSONB NOT NULL DEFAULT '[]'::jsonb
            """
        )
        connection.execute(
            """
            CREATE INDEX IF NOT EXISTS ada_chat_messages_session_id_idx
            ON ada_chat_messages (session_id, id)
            """
        )
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS ada_memories (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                session_id TEXT NOT NULL,
                text TEXT NOT NULL,
                category TEXT NOT NULL,
                ts DOUBLE PRECISION NOT NULL
            )
            """
        )
        connection.execute(
            """
            ALTER TABLE ada_memories
            ADD COLUMN IF NOT EXISTS session_id TEXT NOT NULL DEFAULT 'legacy'
            """
        )
        connection.execute("DROP INDEX IF EXISTS ada_memories_text_lower_idx")
        connection.execute(
            """
            CREATE UNIQUE INDEX IF NOT EXISTS ada_memories_session_text_lower_idx
            ON ada_memories (session_id, lower(text))
            """
        )
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS ada_uploads (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                session_id TEXT NOT NULL,
                filename TEXT NOT NULL,
                content_type TEXT NOT NULL,
                content BYTEA NOT NULL,
                extracted_text TEXT NOT NULL DEFAULT '',
                size_bytes BIGINT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )
            """
        )
        connection.execute(
            """
            ALTER TABLE ada_uploads
            ADD COLUMN IF NOT EXISTS extracted_text TEXT NOT NULL DEFAULT ''
            """
        )
        connection.execute(
            """
            CREATE INDEX IF NOT EXISTS ada_uploads_session_created_idx
            ON ada_uploads (session_id, created_at DESC, id DESC)
            """
        )

    def get_history(self, session_id: str, limit: int = 8) -> list[dict]:
        """Return the most recent messages in chronological order."""
        with self._connection() as connection:
            rows = connection.execute(
                """
                SELECT role, content, sources
                FROM (
                    SELECT id, role, content, sources
                    FROM ada_chat_messages
                    WHERE session_id = %s
                    ORDER BY id DESC
                    LIMIT %s
                ) AS recent
                ORDER BY id
                """,
                (session_id, max(1, min(int(limit), 1000))),
            ).fetchall()
        return [
            {"role": role, "content": content, "sources": sources or []}
            for role, content, sources in rows
        ]

    def append_turn(
        self,
        session_id: str,
        question: str,
        answer: str,
        sources: list[dict] | None = None,
    ) -> None:
        """Persist a chat turn and optional citations in one transaction."""
        encoded_sources = json.dumps(sources or [])
        with self._connection() as connection:
            connection.execute(
                """
                INSERT INTO ada_chat_messages (session_id, role, content, sources)
                VALUES
                    (%s, %s, %s, '[]'::jsonb),
                    (%s, %s, %s, %s::jsonb)
                """,
                (
                    session_id,
                    "user",
                    question,
                    session_id,
                    "assistant",
                    answer,
                    encoded_sources,
                ),
            )

    def clear_history(self, session_id: str) -> None:
        """Delete only the current browser session's stored conversation."""
        with self._connection() as connection:
            connection.execute(
                "DELETE FROM ada_chat_messages WHERE session_id = %s",
                (session_id,),
            )

    def add_upload(
        self,
        session_id: str,
        filename: str,
        content_type: str,
        content: bytes,
        extracted_text: str | None = None,
    ) -> None:
        """Store an uploaded file and any extracted text for its browser session."""
        with self._connection() as connection:
            connection.execute(
                """
                INSERT INTO ada_uploads
                    (session_id, filename, content_type, content, extracted_text, size_bytes)
                VALUES (%s, %s, %s, %s, %s, %s)
                """,
                (
                    session_id,
                    filename,
                    content_type,
                    content,
                    extracted_text or "",
                    len(content),
                ),
            )

    def get_upload_context(
        self, session_id: str, max_chars: int = 8000
    ) -> str:
        """Return a bounded excerpt of this session's readable uploaded documents."""
        with self._connection() as connection:
            rows = connection.execute(
                """
                SELECT id, filename, extracted_text,
                       CASE
                           WHEN extracted_text = '' AND right(lower(filename), 5) = '.docx'
                           THEN content
                           ELSE NULL
                       END
                FROM ada_uploads
                WHERE session_id = %s
                  AND (
                      extracted_text <> ''
                      OR right(lower(filename), 5) = '.docx'
                  )
                ORDER BY created_at DESC, id DESC
                """,
                (session_id,),
            ).fetchall()

        remaining = max(0, max_chars)
        sections = []
        for upload_id, filename, extracted_text, content in rows:
            if not extracted_text and content is not None:
                try:
                    extracted_text = extract_document_text(filename, bytes(content)) or ""
                except ValueError:
                    LOGGER.warning("Could not extract text from uploaded document %s", filename)
                    continue
                if extracted_text:
                    with self._connection() as connection:
                        connection.execute(
                            """
                            UPDATE ada_uploads
                            SET extracted_text = %s
                            WHERE id = %s AND session_id = %s
                            """,
                            (extracted_text, upload_id, session_id),
                        )
            if not remaining:
                break
            if not extracted_text:
                continue
            prefix = f"### {filename}\n"
            excerpt_limit = max(0, remaining - len(prefix))
            excerpt = extracted_text[:excerpt_limit]
            remaining -= len(prefix) + len(excerpt)
            if len(excerpt) < len(extracted_text):
                excerpt += "\n[Document excerpt truncated.]"
            sections.append(prefix + excerpt)

        return "\n\n".join(sections)

    def list_uploads(self, session_id: str) -> list[dict]:
        """List names and sizes without returning uploaded file contents."""
        with self._connection() as connection:
            rows = connection.execute(
                """
                SELECT filename, content_type, size_bytes, created_at,
                       extracted_text <> ''
                FROM ada_uploads
                WHERE session_id = %s
                ORDER BY created_at DESC, id DESC
                """,
                (session_id,),
            ).fetchall()
        return [
            {
                "name": filename,
                "content_type": content_type,
                "size": size_bytes,
                "created_at": created_at.isoformat(),
                "readable": is_readable,
            }
            for filename, content_type, size_bytes, created_at, is_readable in rows
        ]

    def session_knowledge(self, session_id: str) -> dict:
        """Count what this chat session has learned for the orb display."""
        with self._connection() as connection:
            row = connection.execute(
                """
                SELECT
                    (SELECT count(*) FROM ada_memories WHERE session_id = %s) AS memories,
                    (SELECT count(*) FROM ada_uploads
                     WHERE session_id = %s AND extracted_text <> '') AS uploads,
                    (SELECT count(DISTINCT value->>'source')
                     FROM ada_chat_messages AS m,
                          jsonb_array_elements(m.sources) AS elem(value)
                     WHERE m.session_id = %s
                       AND m.role = 'assistant'
                       AND jsonb_typeof(value) = 'object'
                       AND value->>'source' IS NOT NULL
                       AND value->>'source' <> '') AS sources
                """,
                (session_id, session_id, session_id),
            ).fetchone()
        memories, uploads, sources = int(row[0]), int(row[1]), int(row[2])
        return {
            "memories": memories,
            "skills": 0,
            "uploads": uploads,
            "sources": sources,
            "connections": memories + uploads + sources,
        }


class PostgresMemory:
    """Implement Ada's existing memory interface on top of PostgreSQL."""

    def __init__(self, state: PostgresState, session_id: str = "cli"):
        self.state = state
        self.session_id = session_id

    @staticmethod
    def _normalize_item(text: str, category: str = "other", ts: float | None = None) -> dict:
        """Return the same normalized dictionary shape as the local Memory class."""
        clean_text = " ".join(str(text).split()).strip()
        clean_category = str(category or "other").strip().lower()
        if clean_category not in CATEGORIES:
            clean_category = "other"
        return {
            "text": clean_text,
            "category": clean_category,
            "ts": float(ts if ts is not None else time.time()),
        }

    def add(self, fact: str, category: str = "other") -> bool:
        """Insert a unique memory, upgrading an existing generic category if needed."""
        item = self._normalize_item(fact, category)
        if not item["text"]:
            return False
        with self.state._connection() as connection:
            inserted = connection.execute(
                """
                INSERT INTO ada_memories (session_id, text, category, ts)
                VALUES (%s, %s, %s, %s)
                ON CONFLICT DO NOTHING
                RETURNING id
                """,
                (self.session_id, item["text"], item["category"], item["ts"]),
            ).fetchone()
            if inserted:
                return True
            if item["category"] != "other":
                connection.execute(
                    """
                    UPDATE ada_memories
                    SET category = %s
                    WHERE session_id = %s
                      AND lower(text) = lower(%s)
                      AND category = 'other'
                    """,
                    (item["category"], self.session_id, item["text"]),
                )
        return False

    def forget(self, query: str) -> list[str]:
        """Remove memories containing the requested text, case-insensitively."""
        needle = " ".join((query or "").split()).strip().lower()
        if not needle:
            return []
        with self.state._connection() as connection:
            rows = connection.execute(
                """
                DELETE FROM ada_memories
                WHERE session_id = %s
                  AND position(%s in lower(text)) > 0
                RETURNING text
                """,
                (self.session_id, needle),
            ).fetchall()
        return [row[0] for row in rows]

    def all(self) -> list[dict]:
        """Return memories in insertion order using the local memory shape."""
        with self.state._connection() as connection:
            rows = connection.execute(
                """
                SELECT text, category, ts
                FROM ada_memories
                WHERE session_id = %s
                ORDER BY id
                """,
                (self.session_id,),
            ).fetchall()
        return [self._normalize_item(text, category, ts) for text, category, ts in rows]

    def prompt(self) -> str:
        """Format memories for inclusion in an Ada system prompt."""
        lines = []
        for item in self.all():
            category = item["category"]
            label = f"[{category}] " if category != "other" else ""
            lines.append(f"- {label}{item['text']}")
        return "\n".join(lines)

    def suggest_category(self, fact: str) -> str:
        """Reuse the local category heuristics without loading a JSON memory file."""
        from .memory import Memory

        return Memory.suggest_category(fact)

    def __iter__(self):
        return (item["text"] for item in self.all())

    def __len__(self) -> int:
        with self.state._connection() as connection:
            row = connection.execute(
                "SELECT count(*) FROM ada_memories WHERE session_id = %s",
                (self.session_id,),
            ).fetchone()
        return int(row[0])
