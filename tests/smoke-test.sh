#!/usr/bin/env bash
# Smoke test for the deployed system. Run it from OUTSIDE the VPC (Cloud Shell
# or your laptop), otherwise the blocked-port check doesn't mean anything:
#
#   LB_URL=http://<edge-external-ip> ./tests/smoke-test.sh
#
# What it checks (pass/fail criteria in brackets)
#   1. the site answers through the load balancer [GET / and /healthz give 200]
#   2. the document index is loaded [/api/rag/status reports at least 25 chunks]
#   3. a question with a known answer is answered from our documents [the
#      answer contains the fact AND the cited sources include the right file].
#      The answer is generated by the inference replicas, so this also shows
#      the AI tier is working.
#   4. internal ports are blocked from the internet [no connection to the
#      database, inference, or monitoring ports]
#
# Settings (env vars):
#   LB_URL            required, e.g. http://34.1.2.3
#   KNOWN_QUESTION    default "How many centimetres are in one inch?"
#   EXPECTED          text the answer must contain (default 2.54)
#   EXPECTED_SOURCE   text the cited sources must contain (default known-facts-units)
#   MIN_CHUNKS        default 25
#   BLOCKED_PORTS     default "5432 11434 11435 8401 9090 3000"
#
# The question comes from corpus/known-facts-units.md. The output is saved in
# tests/results/ (commit it).

set -uo pipefail

: "${LB_URL:?set LB_URL, e.g. http://34.1.2.3}"
KNOWN_QUESTION="${KNOWN_QUESTION:-How many centimetres are in one inch?}"
EXPECTED="${EXPECTED:-2.54}"
EXPECTED_SOURCE="${EXPECTED_SOURCE:-known-facts-units}"
MIN_CHUNKS="${MIN_CHUNKS:-25}"
BLOCKED_PORTS="${BLOCKED_PORTS:-5432 11434 11435 8401 9090 3000}"
RESULTS_DIR="${RESULTS_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/results}"

mkdir -p "$RESULTS_DIR"
LOG="$RESULTS_DIR/smoke-$(date +%Y%m%d-%H%M%S).log"
exec > >(tee -a "$LOG") 2>&1

FAILED=0
pass() { echo "PASS: $*"; }
fail() { echo "FAIL: $*"; FAILED=1; }

HOST="${LB_URL#*://}"
HOST="${HOST%%[:/]*}"

echo "=== Smoke test ==="
echo "date:    $(date -Is)"
echo "target:  $LB_URL"
echo "AI tool: Claude (helped write this script; prompts are in the test record)"
echo

echo "--- 1. Front end through the load balancer ---"
for path in / /healthz; do
    code="$(curl -s -o /dev/null -w '%{http_code}' --max-time 15 "$LB_URL$path" || true)"
    code="${code:-000}"
    if [[ "$code" == "200" ]]; then
        pass "GET $path returned 200"
    else
        fail "GET $path returned $code"
    fi
done

echo "--- 2. Document index ---"
status_json="$(curl -s --max-time 15 "$LB_URL/api/rag/status" || true)"
echo "status: $status_json"
chunks="$(python3 -c 'import json,sys; print(json.load(sys.stdin).get("chunks", 0))' <<<"$status_json" 2>/dev/null || echo 0)"
if [[ "$chunks" =~ ^[0-9]+$ ]] && (( chunks >= MIN_CHUNKS )); then
    pass "index has $chunks chunks (need $MIN_CHUNKS)"
else
    fail "index has '$chunks' chunks (need $MIN_CHUNKS)"
fi

echo "--- 3. Known-answer question ---"
echo "question: $KNOWN_QUESTION"
ask() {
    python3 - "$LB_URL" "$KNOWN_QUESTION" "$EXPECTED" "$EXPECTED_SOURCE" <<'PY'
import json
import sys
import time
import urllib.error
import urllib.request

base, question, expected, source = sys.argv[1:5]
request = urllib.request.Request(
    base.rstrip("/") + "/api/rag/chat",
    data=json.dumps({"message": question}).encode("utf-8"),
    headers={"Content-Type": "application/json"},
)

start = time.monotonic()
first_token = None
events = []
event, data = None, []
served_by = "unknown"
try:
    with urllib.request.urlopen(request, timeout=180) as response:
        served_by = response.headers.get("X-Served-By", "unknown")
        for raw in response:
            line = raw.decode("utf-8").rstrip("\r\n")
            if line.startswith("event:"):
                event = line[6:].strip()
            elif line.startswith("data:"):
                data.append(line[5:].lstrip())
            elif line == "":
                if event:
                    if event == "token" and first_token is None:
                        first_token = time.monotonic() - start
                    events.append((event, "\n".join(data)))
                event, data = None, []
except (urllib.error.URLError, OSError) as exc:
    print(f"request failed: {exc}")
    sys.exit(1)

print(f"served by: {served_by}")
if first_token is not None:
    print(f"time to first token: {first_token:.1f}s")

error = next((d for e, d in events if e == "error"), None)
if error:
    print(f"stream error: {error}")
    sys.exit(1)
done = next((json.loads(d) for e, d in events if e == "done"), None)
if done is None:
    print("the stream ended without a 'done' event")
    sys.exit(1)

answer = done.get("answer", "")
sources = [s.get("source", "") for s in done.get("sources", [])]
print("answer: " + answer[:300].replace("\n", " "))
print("sources: " + (", ".join(sources) or "none"))

ok = True
if expected.lower() not in answer.lower():
    print(f"the answer does not contain '{expected}'")
    ok = False
if not any(source in s for s in sources):
    print(f"the cited sources do not include '{source}'")
    ok = False
sys.exit(0 if ok else 1)
PY
}

ok=0
for attempt in 1 2 3; do
    echo "attempt $attempt"
    if ask; then ok=1; break; fi
    echo "(the model's wording varies and the first request can be slow; retrying)"
done
if [[ $ok -eq 1 ]]; then
    pass "correct answer with the right source cited"
else
    fail "no correct, cited answer after 3 attempts"
fi

echo "--- 4. Internal ports are blocked from outside ---"
for port in $BLOCKED_PORTS; do
    if timeout 4 bash -c "exec 3<>/dev/tcp/$HOST/$port" 2>/dev/null; then
        fail "port $port is reachable from here (it must be blocked)"
    else
        pass "port $port is not reachable"
    fi
done

echo
if [[ $FAILED -eq 0 ]]; then echo "RESULT: PASS"; else echo "RESULT: FAIL"; fi
exit $FAILED
